#!/usr/bin/env node
"use strict";

/**
 * DriverLens desktop — bundle, CSP and "no browser-helper" static tests (Task 11).
 *
 * Run from the repository root:
 *   node desktop/tests/bundle.test.cjs
 *
 * Uses only Node built-ins (node:test, node:assert) — no new dependencies.
 * The file is intentionally a standalone node:test file, NOT a vitest file:
 * if the desktop vitest suite (default include matches *.test.cjs) picks it
 * up, exclude it via `test.exclude` in desktop/vite.config.ts — a node:test
 * file cannot opt itself out of vitest collection from inside the file.
 *
 * What this proves (static, no app rebuild required):
 *   a. tauri.conf.json ships a strict production CSP: no wildcards, no
 *      https: sources, no telemetry/analytics hosts, and http: only for the
 *      documented Tauri IPC origin. Tauri v2 on Windows serves the ipc
 *      custom protocol as http://ipc.localhost (the same
 *      `http://<scheme>.localhost` wry workaround as `http://tauri.localhost`
 *      for the app origin; see scripts/core.js convertFileSrc and
 *      AppManager::tauri_protocol_url in tauri v2.12.1); the bare `ipc:`
 *      scheme covers the equivalent custom-scheme hosts. The exact pair
 *      `ipc: http://ipc.localhost` is the value the official docs example
 *      (https://v2.tauri.app/security/csp/) uses for connect-src and the
 *      value Tauri's own v1->v2 migration writes into connect-src.
 *   b. The dev/prod CSP split (csp vs devCsp) keeps dev-only allowances
 *      ('unsafe-inline', ws://localhost:1420) out of the production CSP.
 *      Runtime selection is `dev_csp.or(csp)` in dev, `csp` in production
 *      (tauri v2.12.1 AppManager::csp()).
 *   c. The bundle ships exactly one resource — the collector script — plus
 *      icons under icons/; no report/log/.env/fixture/node_modules entries
 *      anywhere in the bundle config.
 *   d. desktop/dist (when present; rebuilt concurrently by another agent —
 *      reads are snapshot-based with one retry) contains NO '8781',
 *      NO 'localhost', NO fetch() to external origins, NO 'server.cjs'.
 *   e. src-tauri/src contains no HTTP server code ('createServer',
 *      'listen(', '8781') and no shell/http/fs plugin crates: shell/http are
 *      absent from Cargo.lock entirely, and tauri-plugin-fs may only appear
 *      as a transitive dependency of tauri-plugin-dialog (Rust-side only;
 *      the renderer is granted no fs/dialog permission in capabilities).
 *   f. capabilities/default.json grants exactly core:default + the nine
 *      allow-<command> permissions to the 'main' window only, with no
 *      fs/http/shell/process/dialog permissions; the nine autogenerated
 *      permission files map 1:1 to the nine backend commands.
 *   g. No 'server.cjs' / 'Start-DriverLens' / '8781' / 'pwsh-helper'
 *      references exist in desktop/src or desktop/src-tauri/src *executable
 *      code*. Comment stripping is applied first — comments cannot create a
 *      runtime dependency — and comment-only mentions are reported for
 *      transparency, never silently ignored.
 */

