const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

// desktop/tests -> repo root
const ROOT = path.resolve(__dirname, "..", "..");
const DESKTOP = path.join(ROOT, "desktop");
const TAURI_DIR = path.join(DESKTOP, "src-tauri");
const TAURI_CONF_PATH = path.join(TAURI_DIR, "tauri.conf.json");
const CAPABILITY_PATH = path.join(TAURI_DIR, "capabilities", "default.json");
const AUTOGEN_PERMS_DIR = path.join(TAURI_DIR, "permissions", "autogenerated");
const CARGO_TOML_PATH = path.join(TAURI_DIR, "Cargo.toml");
const CARGO_LOCK_PATH = path.join(TAURI_DIR, "Cargo.lock");
const DIST_DIR = path.join(DESKTOP, "dist");
const RENDERER_SRC = path.join(DESKTOP, "src");
const RUST_SRC = path.join(TAURI_DIR, "src");

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// ------------------------------------------------------------------ helpers

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function listFiles(dir) {
  const out = [];
  const walk = (base) => {
    for (const entry of fs.readdirSync(base, { withFileTypes: true })) {
      if (entry.name === "node_modules" || entry.name === ".git") continue;
      const abs = path.join(base, entry.name);
      if (entry.isDirectory()) walk(abs);
      else if (entry.isFile()) out.push(abs);
    }
  };
  walk(dir);
  return out.sort();
}

/**
 * Tolerant tree snapshot: [{ rel, text }] or null when the directory is
 * missing or a concurrent writer raced the read. Retries once internally
 * (the directory is being rebuilt by another agent elsewhere in the flow).
 */
function snapshotTree(dir) {
  if (!fs.existsSync(dir)) return null;
  for (let attempt = 0; attempt < 2; attempt++) {
    const before = listFiles(dir);
    const files = [];
    let raced = false;
    for (const abs of before) {
      try {
        files.push({
          rel: path.relative(dir, abs).split(path.sep).join("/"),
          text: fs.readFileSync(abs, "utf8"),
        });
      } catch {
        raced = true;
        break;
      }
    }
    if (!raced) {
      const after = listFiles(dir);
      if (before.length === after.length && before.every((p, i) => p === after[i])) {
        return files;
      }
    }
  }
  return null;
}

/**
 * Normalize a Tauri `Csp` (string form or directive-map form) into a
 * Map<directive, string[]>.
 */
function cspToDirectives(csp) {
  const map = new Map();
  if (typeof csp === "string") {
    for (const part of csp.split(";")) {
      const tokens = part.trim().split(/\s+/).filter(Boolean);
      if (tokens.length === 0) continue;
      map.set(tokens[0].toLowerCase(), tokens.slice(1));
    }
  } else if (csp && typeof csp === "object") {
    for (const [directive, sources] of Object.entries(csp)) {
      const list = (Array.isArray(sources) ? sources : [sources])
        .filter((s) => typeof s === "string" && s.trim())
        .flatMap((s) => s.trim().split(/\s+/));
      map.set(directive.toLowerCase(), list);
    }
  }
  return map;
}

function directivesToString(map) {
  return [...map.entries()].map(([d, s]) => `${d} ${s.join(" ")}`).join("; ");
}

/**
 * Strip comments before scanning for tokens that must never appear in
 * executable code. Heuristic by design (a guard scan, not a parser):
 *  - block comments are removed first (flat, non-nesting),
 *  - then each line is cut at the first '//' that is not part of a URL
 *    scheme, so `"tauri://localhost"` inside a string literal survives,
 *  - with { hash: true } the first '#' cuts the line (TOML).
 * Anything found in raw text but not in stripped code is reported as a
 * comment-only mention.
 */
function stripComments(text, { hash = false } = {}) {
  let out = text.replace(/\/\*[\s\S]*?\*\//g, " ");
  out = out
    .split(/\r?\n/)
    .map((line) => {
      if (hash) {
        const h = line.indexOf("#");
        return h === -1 ? line : line.slice(0, h);
      }
      let i = 0;
      for (;;) {
        const idx = line.indexOf("//", i);
        if (idx === -1) return line;
        if (idx > 0 && line[idx - 1] === ":") {
          i = idx + 2;
          continue;
        }
        return line.slice(0, idx);
      }
    })
    .join("\n");
  return out;
}

function tomlSections(text) {
  const sections = {};
  let current = "";
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*\[([^\]]+)\]\s*$/);
    if (m) {
      current = m[1];
      sections[current] = sections[current] || [];
      continue;
    }
    (sections[current] = sections[current] || []).push(line);
  }
  return sections;
}

function parseLockPackages(lockText) {
  return lockText
    .split("[[package]]")
    .slice(1)
    .map((block) => {
      const name = (block.match(/^name = "([^"]+)"/m) || [])[1];
      const depsBlock = (block.match(/^dependencies = \[([\s\S]*?)\]/m) || [])[1] || "";
      const deps = [...depsBlock.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
      return { name, deps };
    })
    .filter((p) => p.name);
}

const depMatches = (deps, crate) => deps.some((d) => d === crate || d.startsWith(crate + " "));

// -------------------------------------------------------------- a) prod CSP

test("tauri.conf.json: production CSP is minimal and strict", () => {
  const conf = readJson(TAURI_CONF_PATH);
  const cspRaw = conf?.app?.security?.csp;
  assert.ok(cspRaw != null, "app.security.csp must be set (it was null before Task 11)");

  const directives = cspToDirectives(cspRaw);
  const csp = directivesToString(directives);

  // No wildcards, no https:, no telemetry/analytics/CDN hosts.
  assert.ok(!csp.includes("*"), `CSP must not contain wildcards: ${csp}`);
  assert.ok(!csp.toLowerCase().includes("https:"), `CSP must not contain https: sources: ${csp}`);
  for (const host of ["google", "analytics", "telemetry", "sentry", "cdn."]) {
    assert.ok(!csp.toLowerCase().includes(host), `CSP must not reference '${host}': ${csp}`);
  }

  // http: only for the documented Tauri v2 IPC origin (Windows form).
  for (const m of csp.matchAll(/http:\/\/[^\s;]*/gi)) {
    assert.equal(m[0], "http://ipc.localhost", `only the documented IPC origin may use http://: ${m[0]}`);
  }
  // 'localhost' may appear only inside that exact token.
  const lowered = csp.toLowerCase();
  assert.equal(
    (lowered.match(/localhost/g) || []).length,
    (lowered.match(/http:\/\/ipc\.localhost/g) || []).length,
    `'localhost' outside the IPC origin: ${csp}`,
  );

  // No dev-only allowances leaked into production.
  for (const forbidden of ["'unsafe-inline'", "'unsafe-eval'", "'unsafe-hashes'", "ws:", "wss:"]) {
    assert.ok(!csp.includes(forbidden), `production CSP must not contain ${forbidden}: ${csp}`);
  }

  // Exact minimal directive set (docs: https://v2.tauri.app/security/csp/).
  assert.deepEqual(
    [...directives.keys()].sort(),
    ["connect-src", "default-src", "script-src", "style-src"],
    `exact directive set: ${csp}`,
  );
  assert.deepEqual(directives.get("default-src"), ["'self'"]);
  assert.deepEqual(directives.get("connect-src"), ["ipc:", "http://ipc.localhost"]);
  assert.deepEqual(directives.get("script-src"), ["'self'"]);
  assert.deepEqual(directives.get("style-src"), ["'self'"]);
});

// ------------------------------------------------------- b) dev/prod split

test("tauri.conf.json: dev CSP split keeps dev-only allowances out of production", () => {
  const conf = readJson(TAURI_CONF_PATH);
  const security = conf?.app?.security ?? {};
  const prod = directivesToString(cspToDirectives(security.csp));

  assert.ok(
    security.devCsp != null,
    "app.security.devCsp must be set so dev-only allowances can never leak into the production csp",
  );
  const dev = directivesToString(cspToDirectives(security.devCsp));

  // Explicit leak check: production carries none of the dev-only sources.
  for (const leak of ["unsafe-inline", "unsafe-eval", "ws://", "localhost:1420", "http://localhost"]) {
    assert.ok(!prod.includes(leak), `production CSP leaked dev allowance '${leak}': ${prod}`);
  }

  // Dev CSP: no wildcards / https; IPC origins retained for the dev-injection path.
  assert.ok(!dev.includes("*"), `devCsp must not contain wildcards: ${dev}`);
  assert.ok(!dev.toLowerCase().includes("https:"), `devCsp must not contain https: sources: ${dev}`);
  assert.ok(
    dev.includes("ipc:") && dev.includes("http://ipc.localhost"),
    `devCsp must keep the IPC origins: ${dev}`,
  );

  // The only origins allowed in devCsp: the IPC pair and the local Vite server.
  const allowed = new Set(["http://ipc.localhost", "http://localhost:1420", "ws://localhost:1420"]);
  for (const m of dev.matchAll(/(?:https?|wss?):\/\/[^\s;]*/gi)) {
    assert.ok(allowed.has(m[0]), `devCsp has an unexpected origin: ${m[0]}`);
  }
  // Dev essentials present, proving the allowances live here (not nowhere).
  assert.ok(dev.split(/[;\s]+/).includes("'unsafe-inline'"), "devCsp: 'unsafe-inline' for the Vite React preamble / HMR style injection");
  assert.ok(
    dev.split(";").some((d) => d.trim().startsWith("connect-src") && d.includes("ws://localhost:1420")),
    "devCsp: HMR websocket origin",
  );
});

// --------------------------------------------------------- c) bundle config

test("tauri.conf.json: bundle ships only the collector script (plus icons)", () => {
  const conf = readJson(TAURI_CONF_PATH);
  const bundle = conf?.bundle;
  assert.ok(bundle && typeof bundle === "object", "bundle config present");

  assert.deepEqual(
    bundle.resources,
    ["resources/Collect-DriverLens.ps1"],
    "exactly one bundled resource (the collector script)",
  );
  for (const r of bundle.resources) {
    assert.ok(r.startsWith("resources/"), `resource must live under resources/: ${r}`);
  }

  if (bundle.icon != null) {
    assert.ok(Array.isArray(bundle.icon) && bundle.icon.length > 0, "icon list is a non-empty array");
    for (const icon of bundle.icon) {
      assert.ok(icon.startsWith("icons/"), `icon must live under icons/: ${icon}`);
    }
  }

  // No report/log/.env/fixture/node_modules (or similar) entries anywhere in
  // the bundle config — not in resources, not in icons, not in targets.
  const flat = JSON.stringify(bundle).toLowerCase();
  for (const forbidden of ["node_modules", ".env", "fixture", "report", ".log", "logs", "secrets", "test-results"]) {
    assert.ok(!flat.includes(forbidden), `bundle config must not reference '${forbidden}'`);
  }

  // Cross-check: what the config says is what exists on disk, and nothing else.
  const onDisk = fs.readdirSync(path.join(TAURI_DIR, "resources")).sort();
  assert.deepEqual(onDisk, ["Collect-DriverLens.ps1"], "src-tauri/resources/ contains exactly the collector script");
});

// -------------------------------------------------------------- d) dist scan

test("desktop/dist: no helper port, no localhost, no external fetch, no server.cjs", async (t) => {
  // Another agent may be rebuilding dist concurrently: snapshot-based read
  // with one retry (inside snapshotTree) plus one delayed retry on absence.
  let snapshot = snapshotTree(DIST_DIR);
  if (!snapshot || snapshot.length === 0) {
    await sleep(1500);
    snapshot = snapshotTree(DIST_DIR);
  }
  if (!snapshot || snapshot.length === 0) {
    t.diagnostic(
      "desktop/dist is not present (or empty) — scan skipped; the integration wave's production build must recreate it and rerun this file.",
    );
    return;
  }

  for (const { rel, text } of snapshot) {
    assert.ok(!text.includes("8781"), `${rel}: must not contain the browser-helper port 8781`);
    assert.ok(!/localhost/i.test(text), `${rel}: must not contain 'localhost'`);
    assert.ok(!text.includes("server.cjs"), `${rel}: must not reference server.cjs`);
    for (const m of text.matchAll(/fetch\(\s*[`'"](?:https?:)?\/\/[^`'"]*/g)) {
      assert.fail(`${rel}: fetch() to an external origin: ${m[0]}`);
    }
  }
  t.diagnostic(`scanned ${snapshot.length} dist file(s): ${snapshot.map((f) => f.rel).join(", ")}`);
});

// ------------------------------------- e) no HTTP server / plugin crates

test("src-tauri: no HTTP server code, no shell/http/fs plugin crates", () => {
  const snapshot = snapshotTree(RUST_SRC);
  assert.ok(snapshot && snapshot.length > 0, "readable src-tauri/src snapshot");

  for (const { rel, text } of snapshot) {
    if (!rel.endsWith(".rs")) continue;
    const code = stripComments(text);
    for (const token of ["createServer", "listen(", "8781"]) {
      assert.ok(!code.includes(token), `src-tauri/src/${rel}: executable code contains '${token}'`);
    }
  }

  // Cargo.toml: the only UNCONDITIONAL direct tauri-plugin dependency is the
  // dialog plugin (Rust-side dialogs only — no dialog permission is granted
  // to the renderer). Task 12 additionally allows the embedded WebDriver
  // plugin for the native E2E binary — but ONLY as an optional dependency
  // that no default feature activates, so it stays out of the default and
  // release build graphs (see desktop/docs/NATIVE-E2E.md).
  const tomlText = fs.readFileSync(CARGO_TOML_PATH, "utf8");
  const depSection = tomlSections(tomlText).dependencies || [];
  const depLines = depSection
    .map((line) => stripComments(line, { hash: true }))
    .join("\n");
  const directDeps = [...depLines.matchAll(/^\s*([A-Za-z0-9_-]+)\s*=/gm)].map((m) => m[1]);
  for (const crate of ["tauri-plugin-shell", "tauri-plugin-http", "tauri-plugin-fs"]) {
    assert.ok(!directDeps.includes(crate), `Cargo.toml must not depend on ${crate}`);
  }
  const allowedPlugins = ["tauri-plugin-dialog"];
  const wdioCrate = "tauri-plugin-wdio-webdriver";
  if (directDeps.includes(wdioCrate)) {
    const wdioDepLine = depSection
      .map((line) => stripComments(line, { hash: true }))
      .find((line) => new RegExp(`^\\s*${wdioCrate}\\s*=`).test(line));
    assert.match(
      wdioDepLine || "",
      /optional\s*=\s*true/,
      `${wdioCrate} must be an optional dependency (Task 12 E2E feature only)`,
    );
    const featuresLines = tomlSections(tomlText).features || [];
    const featuresSection = featuresLines
      .map((line) => stripComments(line, { hash: true }))
      .join("\n");
    assert.match(
      featuresSection,
      /wdio-e2e\s*=\s*\[[^\]]*dep:tauri-plugin-wdio-webdriver/,
      `${wdioCrate} may only be activated by the wdio-e2e feature`,
    );
    const defaultFeatureLine =
      featuresLines.find((line) => /^\s*default\s*=/.test(line)) || "";
    assert.ok(
      !defaultFeatureLine.includes("wdio"),
      "the default feature set must never activate the E2E WebDriver plugin",
    );
    allowedPlugins.push(wdioCrate);
  }
  assert.deepEqual(
    directDeps.filter((d) => d.startsWith("tauri-plugin-")).sort(),
    allowedPlugins.sort(),
    "only the dialog plugin (plus the optional, feature-gated E2E WebDriver plugin) may be a direct plugin dependency",
  );

  // Cargo.lock: shell/http absent entirely; fs only as a transitive of dialog.
  const packages = parseLockPackages(fs.readFileSync(CARGO_LOCK_PATH, "utf8"));
  const names = new Set(packages.map((p) => p.name));
  assert.ok(!names.has("tauri-plugin-shell"), "Cargo.lock: tauri-plugin-shell absent");
  assert.ok(!names.has("tauri-plugin-http"), "Cargo.lock: tauri-plugin-http absent");
  for (const pkg of packages) {
    if (depMatches(pkg.deps, "tauri-plugin-fs")) {
      assert.equal(
        pkg.name,
        "tauri-plugin-dialog",
        `tauri-plugin-fs may only be pulled transitively by tauri-plugin-dialog (found ${pkg.name})`,
      );
    }
  }
  const rootPkg = packages.find((p) => p.name === "driverlens-desktop");
  assert.ok(rootPkg, "driverlens-desktop present in Cargo.lock");
  for (const crate of ["tauri-plugin-shell", "tauri-plugin-http", "tauri-plugin-fs"]) {
    assert.ok(!depMatches(rootPkg.deps, crate), `lock root package must not depend on ${crate}`);
  }
});

// ------------------------------------------------------- f) capabilities

test("capabilities/default.json: exact permission set, 'main' window only", () => {
  const cap = readJson(CAPABILITY_PATH);
  assert.equal(cap.identifier, "default", "capability identifier");
  assert.deepEqual(cap.windows, ["main"], "capability targets only the main window");
  assert.ok(!("remote" in cap), "capability must not allow remote origins");
  assert.ok(!("platforms" in cap), "no platform widening expected");

  const expected = [
    "core:default",
    "allow-scan-devices",
    "allow-get-scan-state",
    "allow-cancel-scan",
    "allow-open-report",
    "allow-export-report",
    "allow-get-report",
    "allow-get-notebook",
    "allow-save-device-note",
    "allow-clear-notebook",
  ];
  assert.ok(Array.isArray(cap.permissions), "permissions array present");
  assert.deepEqual([...cap.permissions].sort(), [...expected].sort(), "exact permission set");

  // No fs/http/shell/process/dialog permissions, however spelled.
  for (const perm of cap.permissions) {
    const id = typeof perm === "string" ? perm : perm?.identifier ?? "";
    for (const prefix of ["fs", "http", "shell", "process", "dialog"]) {
      assert.ok(!id.startsWith(prefix + ":"), `capability must not grant ${prefix}: permissions (${id})`);
      assert.ok(!id.startsWith("tauri-plugin-" + prefix), `capability must not grant plugin ${prefix} permissions (${id})`);
    }
  }

  // The nine autogenerated permission files map 1:1 to the nine backend commands.
  const expectedCommands = {
    "allow-scan-devices": "scan_devices",
    "allow-get-scan-state": "get_scan_state",
    "allow-cancel-scan": "cancel_scan",
    "allow-open-report": "open_report",
    "allow-export-report": "export_report",
    "allow-get-report": "get_report",
    "allow-get-notebook": "get_notebook",
    "allow-save-device-note": "save_device_note",
    "allow-clear-notebook": "clear_notebook",
  };
  const permFiles = fs.readdirSync(AUTOGEN_PERMS_DIR).filter((f) => f.endsWith(".toml")).sort();
  assert.deepEqual(
    permFiles,
    [
      "cancel_scan.toml",
      "clear_notebook.toml",
      "export_report.toml",
      "get_notebook.toml",
      "get_report.toml",
      "get_scan_state.toml",
      "open_report.toml",
      "save_device_note.toml",
      "scan_devices.toml",
    ],
    "autogenerated permission files",
  );
  for (const [permId, cmd] of Object.entries(expectedCommands)) {
    const file = permFiles.find((f) =>
      fs.readFileSync(path.join(AUTOGEN_PERMS_DIR, f), "utf8").includes(`identifier = "${permId}"`),
    );
    assert.ok(file, `autogenerated permission file for ${permId}`);
    const text = fs.readFileSync(path.join(AUTOGEN_PERMS_DIR, file), "utf8");
    assert.ok(text.includes(`commands.allow = ["${cmd}"]`), `${permId} allows exactly the ${cmd} command`);
  }
});

// ------------------------------------- g) no browser-helper code references

test("desktop/src & src-tauri/src: no browser-helper references in executable code", () => {
  const tokens = ["server.cjs", "Start-DriverLens", "8781", "pwsh-helper"];
  const commentOnly = [];
  const snapshots = new Map();

  for (const dir of [RENDERER_SRC, RUST_SRC]) {
    const snapshot = snapshotTree(dir);
    const relDir = path.relative(ROOT, dir).split(path.sep).join("/");
    assert.ok(snapshot && snapshot.length > 0, `readable snapshot of ${relDir}`);
    snapshots.set(dir, snapshot);
    for (const { rel, text } of snapshot) {
      const code = stripComments(text);
      for (const token of tokens) {
        if (code.includes(token)) {
          assert.fail(
            `${relDir}/${rel}: executable code references '${token}' — the desktop app must not depend on the browser helper`,
          );
        } else if (text.includes(token)) {
          commentOnly.push(`${relDir}/${rel}: '${token}' (comment only)`);
        }
      }
    }
  }

  // The renderer must never spawn processes at all.
  for (const { rel, text } of snapshots.get(RENDERER_SRC)) {
    const code = stripComments(text);
    assert.ok(!/\bchild_process\b/.test(code), `desktop/src/${rel}: renderer must not import child_process`);
    assert.ok(!/\bspawn\s*\(/.test(code), `desktop/src/${rel}: renderer must not spawn processes`);
  }

  if (commentOnly.length > 0) {
    console.log(
      `note: browser-helper tokens mentioned in comments only (not code, not a dependency):\n  - ${commentOnly.join("\n  - ")}`,
    );
  }
});
